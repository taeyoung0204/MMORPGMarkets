WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

-- 기존 주문과 충돌하지 않도록 최초 설치 시 한 번 생성합니다.
DECLARE
    NextOrderID NUMBER;
BEGIN
    SELECT NVL(MAX(OrderID), 0) + 1 INTO NextOrderID FROM PURCHASE_ORDER;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE PURCHASE_ORDER_SEQ START WITH '
        || TO_CHAR(NextOrderID, 'TM9') || ' INCREMENT BY 1 NOCYCLE';
END;
/

-- 완료된 구매 요청과 주문을 연결해 재전송 시 같은 결과를 조회합니다.
CREATE TABLE PURCHASE_REQUEST (
    RequestKey VARCHAR2(36 CHAR) NOT NULL,
    QuoteID    VARCHAR2(36 CHAR) NOT NULL,
    OrderID    NUMBER NOT NULL,
    PRIMARY KEY (RequestKey),
    UNIQUE (OrderID),
    FOREIGN KEY (OrderID) REFERENCES PURCHASE_ORDER(OrderID)
);
